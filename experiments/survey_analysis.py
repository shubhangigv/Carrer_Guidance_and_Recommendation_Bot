"""Survey statistics (questions 1-4, 8, 9): who answered, how clear they are about their career, whether
they had guidance, which field they aim for, and whether they would use a tool like Pathfinder.

Reads   data/raw/survey/responses.csv   (Google Forms -> Responses -> Download .csv; never modified)
Writes  data/processed/survey_clean.csv (tidy copy, git-ignored)
        docs/results/survey/survey_summary.md + charts (*.png): counts only, no individual answers

Run:  python experiments\\survey_analysis.py
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ml.survey import DEFAULT_SURVEY, ANALYSIS_CUTOFF, load_survey  # noqa: E402

OUT_DIR = ROOT / "docs" / "results" / "survey"
CLEAN_FILE = ROOT / "data" / "processed" / "survey_clean.csv"
QUESTIONS = {
    "year": "Q1. Year of study",
    "branch": "Q2. Branch / field of study",
    "clarity": "Q3. Do you feel you are on the right career path?",
    "counsellor": "Q4. Have you used a career counsellor?",
    "aimed_field": "Q8. Which career field are you aiming for?",
    "would_use": "Q9. Would you use an AI career guidance tool?",
}


def table(series):
    counts = series.replace("", "(blank)").value_counts()
    return pd.DataFrame({"answer": counts.index, "count": counts.values,
                         "percent": (counts.values / counts.sum() * 100).round(1)})


def chart(df, title, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(8, 0.45 * len(df) + 1.2))
    ax.barh(df["answer"][::-1], df["count"][::-1], color="#1F5A3C")
    for y, (c, p) in enumerate(zip(df["count"][::-1], df["percent"][::-1])):
        ax.text(c, y, f"  {c} ({p}%)", va="center", fontsize=9)
    ax.set_title(title, fontsize=11, loc="left")
    ax.set_xlabel("Number of students")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--survey", type=Path, default=DEFAULT_SURVEY)
    p.add_argument("--first-n", type=int, default=ANALYSIS_CUTOFF,
                   help="use only the first N responses (default: the analysis cut-off; 0 = all)")
    p.add_argument("--out", type=Path, default=OUT_DIR)
    p.add_argument("--no-charts", action="store_true")
    p.add_argument("--clean-out", type=Path, default=CLEAN_FILE, help="where the tidy copy is written")
    args = p.parse_args(argv)

    tidy = load_survey(args.survey, first_n=args.first_n or None)
    args.clean_out.parent.mkdir(parents=True, exist_ok=True)
    tidy.to_csv(args.clean_out, index=False)
    args.out.mkdir(parents=True, exist_ok=True)

    n = len(tidy)
    lines = [f"# Survey results ({n} responses)", "",
             f"Source: `{args.survey.name}` (Google Form from `tools/create_career_survey.gs`). "
             "Anonymous; counts only. Generated by `experiments/survey_analysis.py` - do not edit by hand.", ""]
    clarity = tidy["clarity"]
    unsure = clarity.isin(["Not sure", "No"]).sum()
    no_help = tidy["counsellor"].isin(["No, never", "No, it wasn't available to me", "Yes, but it didn't help much"]).sum()
    lines += ["## Key numbers", "",
              f"- {unsure} of {n} ({unsure / n * 100:.1f}%) are not sure or do not feel they are on the right career path (Q3).",
              f"- {no_help} of {n} ({no_help / n * 100:.1f}%) never used a counsellor, had none available, or were not helped (Q4).",
              f"- {(tidy['aimed_field'] == 'Not sure yet').sum()} of {n} have not chosen a career field yet (Q8).",
              f"- {(tidy['would_use'] == 'Yes').sum()} of {n} would use an AI career guidance tool; "
              f"{(tidy['would_use'] == 'Maybe').sum()} maybe (Q9).", ""]
    for col, title in QUESTIONS.items():
        t = table(tidy[col])
        lines += [f"## {title}", "", "| Answer | Count | % |", "|---|---|---|"]
        lines += [f"| {a} | {c} | {pc} |" for a, c, pc in t.itertuples(index=False)]
        lines.append("")
        if not args.no_charts:
            chart(t, title, args.out / f"{col}.png")
            lines += [f"![{title}]({col}.png)", ""]
    cross = pd.crosstab(tidy["year"], tidy["clarity"])
    lines += ["## Q3 by year of study", "", "| Year | " + " | ".join(cross.columns) + " |",
              "|---|" + "---|" * len(cross.columns)]
    lines += [f"| {year} | " + " | ".join(str(v) for v in row) + " |" for year, row in zip(cross.index, cross.values)]
    lines.append("")
    (args.out / "survey_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:12]))
    print(f"\nWrote {args.out / 'survey_summary.md'} and the tidy copy {args.clean_out}")


if __name__ == "__main__":
    main()
