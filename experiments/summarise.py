"""Write docs/results/summary.md from the experiment CSVs, so no number is ever copied by hand.

Run after the three experiments (PowerShell, project root):  python experiments\\summarise.py
"""
import argparse
from datetime import date
from pathlib import Path

import pandas as pd

from common import DEFAULT_OUT_DIR

FILES = [
    ("B1. Self-match (synthetic perfect students)", "self_match_summary.csv"),
    ("B2. Weight sensitivity (+/-10% per component)", "weight_sensitivity.csv"),
    ("B3. Masking: naive vs range method", "masking.csv"),
]


def markdown_table(df):
    """A plain Markdown table (no extra package needed)."""
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def main(out_dir=DEFAULT_OUT_DIR):
    out_dir = Path(out_dir)
    parts = [f"# Experiment results (generated by experiments/summarise.py on {date.today()})", "",
             "Synthetic students built from O*NET itself - NOT real students and NOT accuracy. "
             "See README.md in this folder for what each experiment tests and its limitations.", ""]
    for title, name in FILES:
        path = out_dir / name
        parts += [f"## {title}", "", f"Source: `{name}`", ""]
        parts.append(markdown_table(pd.read_csv(path)) if path.exists() else "_Not run yet._")
        parts.append("")
    (out_dir / "summary.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {out_dir / 'summary.md'}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    main(ap.parse_args().out_dir)
